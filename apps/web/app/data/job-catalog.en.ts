export const localizeJobPosition = (position, locale) => {
	if (locale !== 'en-US') return position
	const positionName =
		positionNames[position.positionId] || position.positionName
	return {
		...position,
		positionName,
		description: `Prepare for ${positionName} interviews with role-specific questions, practical scenarios, and competency-focused feedback.`
	}
}
